const labels = {choice:'关于选择',self:'关于自己',relation:'关于关系',life:'关于生活'};
const answers = Object.keys(groups).reduce((all,key) => all.concat(groups[key].map(item => ({id:key+'-'+String(item[0]).padStart(2,'0'),category:key,label:labels[key],text:item[1],reflection:item[2],theme:item[3]}))),[]);
const byId = new Map(answers.map(answer => [answer.id,answer]));
const ANSWER_COUNT = answers.length;
function drawAnswer(category, recentIds, random) {
  const pool = category === 'all' ? answers : answers.filter(item => item.category === category);
  if (!pool.length) throw new Error('Unknown category');
  const recent = (recentIds || []).slice(-8);
  const fresh = pool.filter(item => recent.indexOf(item.id) < 0);
  const candidates = fresh.length ? fresh : pool;
  const recentThemes = new Set(recent.map(id => byId.get(id)).filter(Boolean).slice(-3).map(item => item.theme));
  const varied = candidates.filter(item => !recentThemes.has(item.theme));
  const selection = varied.length ? varied : candidates;
  return selection[Math.min(selection.length-1, Math.floor((random || Math.random)()*selection.length))];
}
module.exports = {answers,drawAnswer,labels,ANSWER_COUNT};
