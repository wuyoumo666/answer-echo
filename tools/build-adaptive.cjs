// Run with Node.js after changing index.wxss or wide-layout.wxss.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const css=fs.readFileSync(path.join(root,'pages/index/index.wxss'),'utf8').replace(/\/\*[\s\S]*?\*\//g,'');
function scope(selector){return selector.split(',').map(raw=>{const s=raw.trim();return s.startsWith('.app-shell')?s.replace('.app-shell','.app-shell.layout-wide'):'.app-shell.layout-wide '+s}).join(',');}
function blocks(text){const result=[];let pos=0;while(pos<text.length){const open=text.indexOf('{',pos);if(open<0)break;const header=text.slice(pos,open).trim();let depth=1,end=open+1;for(;end<text.length&&depth;end++){if(text[end]==='{')depth++;else if(text[end]==='}')depth--;}result.push([header,text.slice(open+1,end-1)]);pos=end;}return result;}
function convert(text,condition){let result='';for(let[header,body]of blocks(text)){
  header=header.replace(/^@import[^;]*;\s*/,'').trim();
  if(header.startsWith('@media')){result+=convert(body,(condition?condition+' and ':'')+header.slice(6).trim());continue;}
  if(header.startsWith('@')||!body.includes('rpx'))continue;
  const rule=scope(header)+'{'+body.replace(/(-?\d*\.?\d+)rpx/g,(_,n)=>Number((Number(n)*.5).toFixed(3))+'px')+'}\n';
  result+=condition?'@media '+condition+'{'+rule+'}\n':rule;
}return result;}
const normalized=convert(css,'(min-width:600px)');
const layout=fs.readFileSync(path.join(__dirname,'wide-layout.wxss'),'utf8');
fs.writeFileSync(path.join(root,'styles/adaptive.wxss'),'/* Generated by tools/build-adaptive.cjs; wide screens use stable 375px design units. */\n'+normalized+'\n'+layout);
console.log('Built wide-screen styles; compact viewport rules remain unchanged.');
